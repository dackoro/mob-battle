"""Morph Wand hologram motion (2026-10-16, user: the panel should move).

Writes Server/Item/Animations/MobBattle_MorphWand.json (Parent Staff, as the Team Wand's set) overriding every
looping Staff entry with copies of its animations plus a "Hologram" node track: the panel floats up and down and
sways a little about its vertical axis, one cycle per loop. The node is the quad in
Common/Items/MobBattle/MorphWand/MobBattle_Hologram.blockymodel; without that attachment the track does nothing.

Run with plain `python scripts/gen-hologram-anims.py` from the repo root (reads Assets.zip of the release install).
Key times are whole frames: every vanilla .blockyanim uses integer times (float times did not play, Effect Wand).
"""
import json
import math
import os
import zipfile

ASSETS = os.path.expandvars(r"$APPDATA\Hytale\install\release\package\game\latest\Assets.zip")
OUT_DIR = "Common/Characters/Animations/Items/MobBattle/MorphHolo"
OUT_REF = "Characters/Animations/Items/MobBattle/MorphHolo"
SET_FILE = "Server/Item/Animations/MobBattle_MorphWand.json"
NODE = "Hologram"
BOB = 3.0        # model units up and down
SWAY_DEG = 14.0  # degrees each way about the panel's vertical axis


def quat_y(deg):
    h = math.radians(deg) / 2
    return {"x": 0.0, "y": round(math.sin(h), 6), "z": 0.0, "w": round(math.cos(h), 6)}


def track(duration):
    """One float/sway cycle over the loop: quarter keys, smooth."""
    times = [round(duration * i / 4) for i in range(5)]
    bob = [0, BOB, 0, -BOB, 0]
    sway = [0, SWAY_DEG, 0, -SWAY_DEG, 0]
    # the sway is a quarter out of step with the bob, so the panel turns while it floats
    sway = sway[1:] + sway[1:2]
    return {
        "position": [{"time": t, "delta": {"x": 0.0, "y": float(b), "z": 0.0}, "interpolationType": "smooth"}
                     for t, b in zip(times, bob)],
        "orientation": [{"time": t, "delta": quat_y(s), "interpolationType": "smooth"} for t, s in zip(times, sway)],
        "shapeStretch": [],
        "shapeVisible": [],
        "shapeUvOffset": [],
    }


def main():
    z = zipfile.ZipFile(ASSETS)
    staff = json.loads(z.read("Server/Item/Animations/Staff.json"))
    os.makedirs(OUT_DIR, exist_ok=True)
    made = {}
    entries = {}
    for name, entry in staff["Animations"].items():
        if not entry.get("Looping"):
            continue
        new = dict(entry)
        for slot in ("ThirdPerson", "ThirdPersonMoving", "FirstPerson"):
            src = entry.get(slot)
            if not src:
                continue
            if src not in made:
                anim = json.loads(z.read("Common/" + src))
                anim["nodeAnimations"][NODE] = track(int(anim["duration"]))
                base = os.path.splitext(os.path.basename(src))[0]
                out = f"{OUT_DIR}/Holo_{base}.blockyanim"
                with open(out, "w", encoding="utf-8", newline="\n") as f:
                    json.dump(anim, f, indent=2)
                made[src] = f"{OUT_REF}/Holo_{base}.blockyanim"
            new[slot] = made[src]
        entries[name] = new
    data = {
        "$Comment": "Morph Wand: the staff's poses (Parent Staff); every looping one copied with a 'Hologram' node "
                    "track (float and sway of the copied mob's hologram panel). Generated by "
                    "scripts/gen-hologram-anims.py (2026-10-16).",
        "Parent": "Staff",
        "Animations": entries,
    }
    with open(SET_FILE, "w", encoding="utf-8", newline="\n") as f:
        json.dump(data, f, indent=1)
    print(f"{len(entries)} entries, {len(made)} animation files")


if __name__ == "__main__":
    main()

"""Effect Wand burst per palette color (2026-10-13, user: the chat line and the wave take the effect's color, the burst on
the mob was always purple).

Writes, for every palette color:
  Server/Particles/MobBattle/Spawners/MobBattle_Effect_<Implosion|Sparks>_<Color>.particlespawner
  Server/Particles/MobBattle/Effect/MobBattle_Effect_Burst_<Color>.particlesystem
  Server/Entity/Effects/MobBattle/Fx/Effect/MobBattle_Fx_Effect_<Color>.json
from the purple originals (MobBattle_Effect_Implosion/Sparks, MobBattle_Fx_Effect). Purple keeps the tuned colors.
EffectGiveInteraction picks the color with EffectWand.colorOf + Teams.nearestPalette. Run with plain python.
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PALETTE = {
    'Red': '#FF4B3E', 'Blue': '#4B9BFF', 'Green': '#4BFF6A', 'Yellow': '#FFD23E', 'Orange': '#FF8C1A',
    'Purple': '#A24BFF', 'Pink': '#FF6BD5', 'Cyan': '#3EF0FF', 'White': '#F2F2F2', 'Black': '#2A2A2A',
    'Brown': '#8B5A2B', 'Lime': '#B6FF3E', 'Gray': '#808080', 'Magenta': '#FF00FF',
}
PARTS = ('Implosion', 'Sparks')

particles = os.path.join(ROOT, 'Server', 'Particles', 'MobBattle')
spawners = os.path.join(particles, 'Spawners')
systems = os.path.join(particles, 'Effect')
effects = os.path.join(ROOT, 'Server', 'Entity', 'Effects', 'MobBattle', 'Fx', 'Effect')
os.makedirs(systems, exist_ok=True)
os.makedirs(effects, exist_ok=True)


def rgb(h):
    return [int(h[i:i + 2], 16) for i in (1, 3, 5)]


def recolor(original, palette):
    """Keeps how pale and how bright the purple was, in the palette color: near white stays near white."""
    v, p = rgb(original), rgb(palette)
    white = min(v) / 255
    bright = max(v) / 255
    out = [round((c * (1 - white) + 255 * white) * bright) for c in p]
    return '#' + ''.join('%02x' % max(0, min(255, c)) for c in out)


def write(path, data):
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(data if isinstance(data, str) else json.dumps(data, indent=2) + '\n')


system = json.load(open(os.path.join(particles, 'MobBattle_Effect_Burst.particlesystem'), encoding='utf-8'))
effect = json.load(open(os.path.join(ROOT, 'Server', 'Entity', 'Effects', 'MobBattle', 'Fx', 'MobBattle_Fx_Effect.json'), encoding='utf-8'))

for color, hexc in PALETTE.items():
    for part in PARTS:
        text = open(os.path.join(spawners, 'MobBattle_Effect_%s.particlespawner' % part), encoding='utf-8').read()
        if color != 'Purple':
            text = re.sub(r'("Color"\s*:\s*")(#[0-9a-fA-F]{6})"', lambda m: m.group(1) + recolor(m.group(2), hexc) + '"', text)
        write(os.path.join(spawners, 'MobBattle_Effect_%s_%s.particlespawner' % (part, color)), text)
    s = dict(system)
    s['Spawners'] = [dict(sp, SpawnerId=sp['SpawnerId'] + '_' + color) for sp in system['Spawners']]
    s['$Comment'] = 'Effect Wand burst in %s. Generated by scripts/gen-effectburst.py.' % color
    write(os.path.join(systems, 'MobBattle_Effect_Burst_%s.particlesystem' % color), s)
    e = json.loads(json.dumps(effect))
    e['$Comment'] = 'Effect Wand burst and sound in %s (the given effect\'s color). Generated by scripts/gen-effectburst.py.' % color
    e['ApplicationEffects']['Particles'][0]['SystemId'] = 'MobBattle_Effect_Burst_' + color
    write(os.path.join(effects, 'MobBattle_Fx_Effect_%s.json' % color), e)
print('wrote', len(PALETTE), 'colors')

"""Build src/main/resources/dev/dackoro/mobbattle/observed-kinds.properties from /mobbattle test verify reports.

Usage: python scripts/gen-observed-kinds.py <verify_full.txt> [<verify_retry.txt> ...]

A role that attacked (hit, or attacked without damage) in any report can fight: it keeps its guessed kind (Fighters or
Defend only), or becomes Fighters if the guess was No attack. A role that never attacked in any report becomes
NO_ATTACK. Only roles whose observed kind differs from the guess are written; PickLists uses them for the game's own
roles instead of its JSON guess. Reports: "role | guessed kind | order X | result [| MISMATCH]".

Kickers (2026-10-14, playtest: cows kick players who hit them): a role that never attacked but has AttackWhenStartled and
an Attack in its role chain (Template_Animal_Neutral: kicks an attacker standing behind it within AttackRange, else
flees) is written as DEFENDS,passive: Defend only on the panel, yet it never starts a fight (passiveWin). The chain is
read from the game's Assets.zip.
"""
import json
import os
import sys
import zipfile
from pathlib import Path

ASSETS = Path(os.path.expandvars("%APPDATA%")) / "Hytale/install/release/package/game/latest/Assets.zip"

# Roles verify cannot judge, so they keep the JSON guess (2026-10-14): aquatic predators only fight in water, goblin
# turrets are static launchers that shoot from afar, Risen are summoned allies that fight beside an owner, and
# Golem_Crystal_Flame's siblings all attacked once given 40 s.
KEEP_GUESS = {"Piranha", "Piranha_Black", "Snapjaw", "Shark_Hammerhead", "Eel_Moray",
              "Goblin_Turret", "Goblin_Lobber_Turret", "Coffer_Goblin_Turret", "Dungeon_Goblin_Turret",
              "Risen_Gunner", "Risen_Knight", "Golem_Crystal_Flame"}

LABELS = {"Fighters": "FIGHTS", "Defend only": "DEFENDS", "No attack": "NO_ATTACK", "Avoid": "AVOID"}


def read(path):
    rows = {}
    for line in Path(path).read_text(encoding="utf-8").splitlines()[1:]:
        parts = [p.strip() for p in line.split(" | ")]
        if len(parts) < 4:
            continue
        role, guess, result = parts[0], parts[1], parts[3]
        attacked = result.startswith("hit ") or result.startswith("attacked")
        rows[role] = (guess, attacked)
    return rows


class Roles:
    """Role JSON chain lookups (Modify, then Parameters default, then the Reference) from Assets.zip."""

    def __init__(self, path):
        self.zip = zipfile.ZipFile(path)
        self.files = {Path(n).stem: n for n in self.zip.namelist()
                      if n.startswith("Server/NPC/Roles/") and n.endswith(".json")}
        self.cache = {}

    def json(self, name):
        if name not in self.cache:
            n = self.files.get(name)
            self.cache[name] = json.loads(self.zip.read(n)) if n else None
        return self.cache[name]

    def value(self, role, key, depth=0):
        j = self.json(role)
        if j is None or depth > 12:
            return None
        mod = j.get("Modify") or {}
        if key in mod:
            return mod[key]
        params = j.get("Parameters") or {}
        if key in params and isinstance(params[key], dict):
            return params[key].get("Value")
        ref = j.get("Reference")
        return self.value(ref, key, depth + 1) if isinstance(ref, str) else None

    def kicker(self, role):
        attack = self.value(role, "Attack")
        return self.value(role, "AttackWhenStartled") is True and isinstance(attack, str) and attack != ""


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    guess, attacked = {}, {}
    for report in sys.argv[1:]:
        for role, (g, a) in read(report).items():
            guess.setdefault(role, g)
            attacked[role] = attacked.get(role, False) or a
    roles = Roles(ASSETS)
    out = {}
    for role, did in sorted(attacked.items()):
        if role in KEEP_GUESS:
            continue
        g = LABELS.get(guess[role])
        if did and g == "NO_ATTACK":
            out[role] = "FIGHTS"
        elif not did and roles.kicker(role):
            out[role] = "DEFENDS,passive"
        elif not did and g != "NO_ATTACK":
            out[role] = "NO_ATTACK"
    target = Path(__file__).resolve().parent.parent / "src/main/resources/dev/dackoro/mobbattle/observed-kinds.properties"
    target.parent.mkdir(parents=True, exist_ok=True)
    lines = ["# Generated by scripts/gen-observed-kinds.py from /mobbattle test verify reports: only roles whose",
             "# observed behaviour differs from PickLists' JSON guess. Game roles only.",
             "# Sources: " + ", ".join(Path(r).name for r in sys.argv[1:])]
    lines += [f"{role}={kind}" for role, kind in out.items()]
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(out)} roles written to {target} ({sum(1 for k in out.values() if k == 'NO_ATTACK')} No attack, "
          f"{sum(1 for k in out.values() if k == 'FIGHTS')} Fighters, "
          f"{sum(1 for k in out.values() if k == 'DEFENDS,passive')} kickers)")


if __name__ == "__main__":
    main()

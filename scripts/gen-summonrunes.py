"""
Generates the summon rune (the circle each summoned mob rises from) in every palette color
(run with: python scripts/gen-summonrunes.py).

Source: the game's Praetorian_Summon_Spawn (Server/Particles/NPC/Skeleton_Burnt_Praetorian in Assets.zip): debris,
a ground crack, a runic circle and lingering sparks. The red is only in the "Color" values (generic textures), so
the crack, circle and sparks are recolored the way gen-crowns.py does; the debris (earth) stays as is. Writes:

  Server/Particles/MobBattle/SummonRune/Spawners/MobBattle_SummonRune_<Color>_<part>.particlespawner
  Server/Particles/MobBattle/SummonRune/MobBattle_SummonRune_<Color>.particlesystem

SummonList picks the color of the summon border (/mobbattle borderColor summon), else the summon wave, else green.
"""
import json
import os
import re
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASSETS = os.path.expandvars(r'%APPDATA%\Hytale\install\pre-release\package\game\latest\Assets.zip')
SOURCE = 'Server/Particles/NPC/Skeleton_Burnt_Praetorian/'
RECOLOR = ('Praetorian_Spawn_Crack', 'Praetorian_Spawn_Circle', 'Praetorian_Spawn_Sparks_Linger')

# Teams.PALETTE
PALETTE = {
    'Red': '#FF4B3E', 'Blue': '#4B9BFF', 'Green': '#4BFF6A', 'Yellow': '#FFD23E', 'Orange': '#FF8C1A',
    'Purple': '#A24BFF', 'Pink': '#FF6BD5', 'Cyan': '#3EF0FF', 'White': '#F2F2F2', 'Black': '#2A2A2A',
    'Brown': '#8B5A2B', 'Lime': '#B6FF3E', 'Gray': '#808080', 'Magenta': '#FF00FF',
}

out = os.path.join(ROOT, 'Server', 'Particles', 'MobBattle', 'SummonRune')
spawners = os.path.join(out, 'Spawners')
os.makedirs(spawners, exist_ok=True)


def rgb(h):
    return [int(h[i:i + 2], 16) for i in (1, 3, 5)]


def recolor(vanilla, palette):
    """Keeps how pale and how bright the red was, in the palette color: white stays white, red becomes the color."""
    v, p = rgb(vanilla), rgb(palette)
    white = min(v) / 255
    bright = max(v) / 255
    c = [round((x * (1 - white) + 255 * white) * bright) for x in p]
    return '#' + ''.join('%02x' % max(0, min(255, x)) for x in c)


def write(path, data):
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(data if isinstance(data, str) else json.dumps(data, indent=2) + '\n')


z = zipfile.ZipFile(ASSETS)
system = json.loads(z.read(SOURCE + 'Praetorian_Summon_Spawn.particlesystem'))
texts = {p: z.read(SOURCE + p + '.particlespawner').decode('utf-8') for p in RECOLOR}

for color, hexc in PALETTE.items():
    def sid(part):
        return 'MobBattle_SummonRune_%s_%s' % (color, part.replace('Praetorian_Spawn_', ''))
    for part, text in texts.items():
        t = re.sub(r'("Color"\s*:\s*")(#[0-9a-fA-F]{6})"', lambda m: m.group(1) + recolor(m.group(2), hexc) + '"', text)
        write(os.path.join(spawners, sid(part) + '.particlespawner'), t)
    sp = [dict(s, SpawnerId=sid(s['SpawnerId'])) if s['SpawnerId'] in RECOLOR else s for s in system['Spawners']]
    write(os.path.join(out, 'MobBattle_SummonRune_%s.particlesystem' % color),
          dict(system, **{'$Comment': 'Praetorian_Summon_Spawn in %s. Generated by scripts/gen-summonrunes.py.' % color},
               Spawners=sp))
print('ok', len(PALETTE))

"""
Generates the Buff Wand's lasting look per palette color (run with: python scripts/gen-bufflook.py):
Server/Entity/Effects/MobBattle/Fx/Buff/MobBattle_Fx_BuffLook_<Color>.json, an Infinite effect with the battle
mark's tint (Fx/Mark/MobBattle_Fx_Mark_<Color>.json) and its aura at the feet (MobBattle_Mark_Aura_<Color>,
a continuous spawner). Buffs puts it on while a mob has the Buff Wand's buff, in /mobbattle buffColor.
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
fx = os.path.join(ROOT, 'Server', 'Entity', 'Effects', 'MobBattle', 'Fx')
out = os.path.join(fx, 'Buff')
os.makedirs(out, exist_ok=True)
n = 0
for name in sorted(os.listdir(os.path.join(fx, 'Mark'))):
    if not name.startswith('MobBattle_Fx_Mark_'):
        continue
    color = name[len('MobBattle_Fx_Mark_'):-len('.json')]
    mark = json.load(open(os.path.join(fx, 'Mark', name), encoding='utf-8'))['ApplicationEffects']
    data = {
        '$Comment': 'Buff Wand: lasting %s tint and aura while the buff lasts (/mobbattle buffColor). Generated by scripts/gen-bufflook.py.' % color,
        'Infinite': True,
        'ApplicationEffects': {
            'EntityTopTint': mark['EntityTopTint'],
            'EntityBottomTint': mark['EntityBottomTint'],
            'Particles': [{'SystemId': 'MobBattle_Mark_Aura_' + color, 'TargetEntityPart': 'Entity'}],
        },
        'OverlapBehavior': 'Overwrite',
        'Debuff': False,
    }
    with open(os.path.join(out, 'MobBattle_Fx_BuffLook_%s.json' % color), 'w', encoding='utf-8', newline='\n') as f:
        f.write(json.dumps(data, indent=2) + '\n')
    n += 1
print(n, 'buff looks')
